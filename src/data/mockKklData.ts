// ---- השלמת דמו: תעודות משלוח סינתטיות להתקשרויות בביצוע שאין להן תעודות בדגימה ההיסטורית ----
// הנתונים אקראיים-דטרמיניסטיים ואינם נתוני אמת (ללא שמות נהגים/לוחיות מזהות).
function enrichExecutingContracts(list: Contract[]): Contract[] {
  const WOOD = ['אורן ירושלים - בולים (מ"ק)', 'מעורב מחטני - בולים (מ"ק)', 'אורן ברוטיה - בולים (מ"ק)', 'אורן ירושלים - עצים להסקה (מ"ק)'];
  const YARDS = ['ביריה', 'אודם'];
  return list.map((c) => {
    if (c.Status !== 'בביצוע' || (c.DeliveryNotes && c.DeliveryNotes.length)) return c;
    let h = 0;
    for (const ch of c.Contract_ID + c.Contract_Name) h = (Math.imul(h, 31) + ch.charCodeAt(0)) >>> 0;
    const rnd = () => { h = (Math.imul(h ^ (h >>> 15), 0x2c1b3c6d) + 0x297a2d39) >>> 0; return (h >>> 8) / 16777216; };
    const count = 8 + Math.floor(rnd() * 15);
    const start = Date.UTC(2026, 0, 5), end = Date.UTC(2026, 9, 30);
    const rems = c.Felling_Licenses.flatMap((f) => f.Removing_Licenses || []);
    const notes: DeliveryNote[] = Array.from({ length: count }, (_, i) => {
      const t = new Date(start + Math.floor(((i + rnd() * 0.8) / count) * (end - start)));
      const date = `${t.toISOString().slice(0, 10)} ${String(6 + Math.floor(rnd() * 10)).padStart(2, '0')}:${String(Math.floor(rnd() * 6) * 10).padStart(2, '0')}`;
      return {
        Delivery_ID: `ת.מ-${2000000 + Math.floor(rnd() * 900000)}`,
        Date: date,
        QuantityMQ: Math.round((12 + rnd() * 14) * 10) / 10,
        WoodType: WOOD[Math.floor(rnd() * WOOD.length)],
        Removing_License_ID: rems.length ? rems[Math.floor(rnd() * rems.length)].Removing_License_ID : '',
        DriverName: 'נהג משאית',
        TruckPlate: `••${100 + Math.floor(rnd() * 900)}`,
        WeighSlipNumber: '-',
        DestinationYard: YARDS[Math.floor(rnd() * YARDS.length)],
        SupervisorSign: 'הונפק ע״י מפקח יערני',
        Notes: 'נתון דמו סינתטי – לא נתון אמת.',
      };
    }).sort((a, b) => a.Date.localeCompare(b.Date));
    return { ...c, DeliveryNotes: notes };
  });
}

